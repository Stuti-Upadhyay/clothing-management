    private void linearSearchProducts() {

    String key = SearchButton.getText().trim();

    if (key.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Enter product name to search");
        return;
    }

    DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
    model.setRowCount(0);

    boolean found = false;

    for (ClothingItems item : controller.getInventory()) {
        if (item.getStock() > 0 &&
            item.getName().equalsIgnoreCase(key)) {

            model.addRow(new Object[]{
                item.getId(),
                item.getName(),
                item.getCategory(),
                item.getSize(),
                item.getPrice(),
                "Add to Cart"
            });

            found = true;
            break; // ← TRUE LINEAR SEARCH
        }
    }

    if (!found) {
        JOptionPane.showMessageDialog(this, "Product not found");
    }
}

    
    private void checkout() {
    if (cart.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Cart is empty!");
        return;
    }

    String name = JOptionPane.showInputDialog(this, "Enter your name:");
    if (name == null || name.trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Name is required");
        return;
    }

    String phone = JOptionPane.showInputDialog(this, "Enter phone number:");
    if (phone == null || !phone.matches("\\d{10}")) {
        JOptionPane.showMessageDialog(this, "Phone must be number");
        return;
    }

    String address = JOptionPane.showInputDialog(this, "Enter address:");
    if (address == null || address.trim().length() < 5) {
        JOptionPane.showMessageDialog(this, "Address too short");
        return;
    }

    for (CartItem c : cart) {
    orderController.addOrder(
        name,
        phone,
        address,
        c.item,
        c.quantity
    );
}


    cart.clear();
    loadCartTable();
    loadProductsTable();

    JOptionPane.showMessageDialog(
        this,
        "Order placed successfully!",
        "Success",
        JOptionPane.INFORMATION_MESSAGE
    );
}

    
    
