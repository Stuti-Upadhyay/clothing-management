    private void loadProductsTable() {
    DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
    model.setRowCount(0); // clear table

    for (ClothingItems item : controller.getInventory()) {
        if (item.getStock() > 0) {
            model.addRow(new Object[]{
                item.getId(),
                item.getName(),
                item.getCategory(),
                item.getSize(),
                item.getPrice(),
                "Add to Cart"
            });
        }
    }
}
    private void addProductTableClick() {
    jTable1.addMouseListener(new java.awt.event.MouseAdapter() {
        @Override
        public void mouseClicked(java.awt.event.MouseEvent evt) {
            int row = jTable1.rowAtPoint(evt.getPoint());
            int col = jTable1.columnAtPoint(evt.getPoint());

            // "Add" column index = 5
            if (col == 5) {
                int id = (int) jTable1.getValueAt(row, 0);
                ClothingItems item = controller.getItemById(id);
                addToCart(item);
            }
        }
    });
    
}
    private void addToCart(ClothingItems item) {
    for (CartItem c : cart) {
        if (c.item.getId() == item.getId()) {
            c.quantity++;
            loadCartTable();

            JOptionPane.showMessageDialog(
                this,
                item.getName() + " quantity increased in cart",
                "Added to Cart",
                JOptionPane.INFORMATION_MESSAGE
            );
            return;
        }
    }

    cart.add(new CartItem(item));
    loadCartTable();

    JOptionPane.showMessageDialog(
        this,
        item.getName() + " added to cart successfully",
        "Added to Cart",
        JOptionPane.INFORMATION_MESSAGE
    );
}


    private void loadCartTable() {
    DefaultTableModel model = (DefaultTableModel) CartTable.getModel();
    model.setRowCount(0);

    double total = 0;

    for (CartItem c : cart) {
        double itemTotal = c.item.getPrice() * c.quantity;
        total += itemTotal;

        model.addRow(new Object[]{
            c.item.getId(),
            c.item.getName(),
            c.item.getPrice(),
            c.quantity,
            itemTotal
        });
    }

    jLabel2.setText("Total : Rs " + total);
}




