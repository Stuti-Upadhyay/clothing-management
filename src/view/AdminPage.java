    private int binarySearchByName(String key) {

    var items = controller.getInventory();

    int low = 0;
    int high = items.size() - 1;

    while (low <= high) {

        int mid = (low + high) / 2;

        int result =
                items.get(mid).getName().compareToIgnoreCase(key);

        if (result == 0) {
            return mid;        // FOUND
        } else if (result < 0) {
            low = mid + 1;     // RIGHT
        } else {
            high = mid - 1;    // LEFT
        }
    }

    return -1; // NOT FOUND
}

    
