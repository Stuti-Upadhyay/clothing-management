 private void selectionSortById() {

    var items = controller.getInventory();
    int n = items.size();

    for (int i = 0; i < n - 1; i++) {

        int minIndex = i;

        for (int j = i + 1; j < n; j++) {
            if (items.get(j).getId() < items.get(minIndex).getId()) {
                minIndex = j;
            }
        }

        // swap
        ClothingItems temp = items.get(minIndex);
        items.set(minIndex, items.get(i));
        items.set(i, temp);
    }

    loadInventoryTable();
}

